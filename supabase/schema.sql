-- 1) أنشئ مشروع Supabase ثم نفّذ هذا الملف من SQL Editor.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  role text not null default 'employee' check (role in ('admin','employee')),
  created_at timestamptz not null default now()
);

create table if not exists public.parts (
  id bigint generated by default as identity primary key,
  part_type text not null check (part_type in ('screen','protector')),
  brand text not null default '',
  name text not null,
  devices text[] not null default '{}',
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.parts enable row level security;

-- كل مستخدم مسجل يستطيع قراءة بيانات الملف الشخصي الخاص به فقط.
drop policy if exists "read own profile" on public.profiles;
create policy "read own profile" on public.profiles
for select to authenticated using (id = auth.uid());

-- المستخدمون المسجلون يستطيعون قراءة كتالوج القطع.
drop policy if exists "authenticated read parts" on public.parts;
create policy "authenticated read parts" on public.parts
for select to authenticated using (true);

-- المدير فقط يستطيع الإضافة والتعديل والحذف.
drop policy if exists "admin insert parts" on public.parts;
create policy "admin insert parts" on public.parts
for insert to authenticated
with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

drop policy if exists "admin update parts" on public.parts;
create policy "admin update parts" on public.parts
for update to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'))
with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

drop policy if exists "admin delete parts" on public.parts;
create policy "admin delete parts" on public.parts
for delete to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

-- لا تسمح للواجهة بتغيير أدوار الحسابات. إنشاء الموظفين يتم عبر Edge Function الآمنة.
revoke all on public.profiles from anon, authenticated;
grant select on public.profiles to authenticated;
grant select, insert, update, delete on public.parts to authenticated;
grant usage, select on sequence public.parts_id_seq to authenticated;

